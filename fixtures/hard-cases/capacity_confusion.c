/* Synthetic CAP1 archive renderer used by tests/test_capacity_repair.py.
 *
 * It mirrors the reviewed defect class: the same destination range check is
 * inlined three times and the ``span`` branch checks the destination against
 * the payload-pool size instead of the output buffer size (CWE-131/697/787).
 * ``out_size``/``data_size`` are function arguments, so the compiler keeps the
 * capacities in callee-saved registers -- the register-allocated shape the
 * reviewed repair engine covers.  A guard word after the output allocation
 * makes the overflow observable ("output guard corrupt") without a crash.
 *
 * Build (Lima x86-64 cross toolchain, see README/toolchain report):
 *   x86_64-linux-gnu-gcc-13 -O2 -static -fno-pie -no-pie -s \
 *       -o fixtures/hard-cases/vuln-capacity-param-x86_64.elf \
 *       fixtures/hard-cases/capacity_confusion.c
 *
 * Archives are generated by fixtures/hard-cases/gen_capacity_archives.py.
 * Reference repair: the ``span`` destination check must use ``out_size``.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

struct op { unsigned kind, dst, src, len, aux; };

static void die(const char *msg) { fprintf(stderr, "%s\n", msg); exit(1); }
static int range_ok(unsigned off, unsigned len, unsigned cap) { return off <= cap && len <= cap - off; }

void render(unsigned flags, unsigned out_size, unsigned data_size, const struct op *ops, unsigned n, const unsigned char *payload, unsigned char *out)
{
    unsigned i;
    for (i = 0; i < n; i++) {
        const struct op *o = &ops[i];
        switch (o->kind) {
        case 0:
            if (!range_ok(o->src, o->len, data_size)) die("literal source outside the payload pool");
            if (!range_ok(o->dst, o->len, out_size)) die("literal destination outside the output");
            memcpy(out + o->dst, payload + o->src, o->len);
            break;
        case 1:
            if (!(flags & 1u)) die("span ops require FLAG_SPARSE");
            if (!range_ok(o->src, o->len, data_size)) die("span source outside the payload pool");
            if (!range_ok(o->dst, o->len, data_size)) die("span destination outside the payload pool");
            memcpy(out + o->dst, payload + o->src, o->len);
            break;
        case 2:
            if (!range_ok(o->dst, o->len, out_size)) die("fill destination outside the output");
            memset(out + o->dst, (int)o->aux, o->len);
            break;
        default: die("unsupported operation kind");
        }
    }
}

static unsigned long get_u32(const unsigned char *p) { return p[0] | (p[1]<<8) | (p[2]<<16) | ((unsigned long)p[3]<<24); }

int main(int argc, char **argv)
{
    FILE *f; long size; unsigned char *raw, *out; struct op *ops; unsigned i, flags, out_size, data_size, n;
    if (argc != 2) { fprintf(stderr, "usage: %s <archive>\n", argv[0]); return 2; }
    f = fopen(argv[1], "rb"); if (!f) die("cannot open archive");
    fseek(f, 0, SEEK_END); size = ftell(f); if (size < 20 || size > (1<<20)) die("bad archive size");
    rewind(f); raw = malloc((size_t)size); if (!raw) die("oom");
    if (fread(raw, 1, (size_t)size, f) != (size_t)size) die("short archive");
    fclose(f);
    if (memcmp(raw, "CAP1", 4)) die("bad magic");
    flags = get_u32(raw+4); out_size = get_u32(raw+8); data_size = get_u32(raw+12); n = get_u32(raw+16);
    if (!out_size || out_size > (1u<<20)) die("bad out_size");
    if (!data_size || data_size > (1u<<16)) die("bad data_size");
    if (!n || n > 64) die("bad operation count");
    if ((unsigned long)size < 20ul + n*20ul + data_size) die("truncated archive");
    ops = calloc(n, sizeof *ops); if (!ops) die("oom");
    for (i = 0; i < n; i++) {
        const unsigned char *p = raw + 20 + (size_t)i*20;
        ops[i].kind = get_u32(p); ops[i].dst = get_u32(p+4); ops[i].src = get_u32(p+8);
        ops[i].len = get_u32(p+12); ops[i].aux = get_u32(p+16);
        if (!ops[i].len) die("bad operation length");
        if (ops[i].kind != 2 && ops[i].aux) die("bad operation auxiliary");
    }
    out = malloc((size_t)out_size + 16); if (!out) die("oom");
    memset(out, 0, (size_t)out_size + 16);
    memset(out + out_size, 0xA5, 16);
    render(flags, out_size, data_size, ops, n, raw + 20 + (size_t)n*20, out);
    for (i = 0; i < 16; i++) if (out[out_size+i] != 0xA5) die("output guard corrupt");
    printf("rendered %u bytes\n", out_size);
    printf("operations:\n");
    for (i = 0; i < n; i++) printf("  op[%u] kind=%u dst=%u src=%u len=%u aux=%u\n", i, ops[i].kind, ops[i].dst, ops[i].src, ops[i].len, ops[i].aux);
    return 0;
}
