def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha256_file(path: Path) -> str:
    return _sha256_bytes(path.read_bytes())


def _canonical_json(value: Any) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _git_sha() -> str:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=str(ROOT),
            capture_output=True, text=True, timeout=20, check=False,
        )
        if result.returncode == 0:
            return result.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        pass
    return "unknown"


def _sample(sample_id: str) -> dict[str, Any]:
    manifest = _load_json(ROOT / MANIFEST_PATH)
    for sample in manifest.get("samples", []):
        if sample.get("sample_id") == sample_id:
            return sample
    raise KeyError(f"sample missing from manifest: {sample_id}")


def _benchmark_result(sample_id: str) -> dict[str, Any]:
    results = _load_json(ROOT / RESULTS_PATH)
    for item in results.get("results", []):
        if item.get("sample_id") == sample_id:
            return item
    raise KeyError(f"sample missing from benchmark results: {sample_id}")


def _target_argument(sample: dict[str, Any]) -> Any:
    target = sample.get("target") or {}
    if target.get("kind") == "va_range":
        return {"va": target["va"], "end": target["end"]}
    return target.get("symbol") or target.get("function")


def _runner_metadata(sample: dict[str, Any]) -> dict[str, Any]:
    """Exactly what the benchmark runner advertises to the verifier (CLI path)."""
    target = sample.get("target") or {}
    scope: dict[str, Any] = {"policy": "target_scoped"}
    if target.get("kind") in {"symbol", "function"}:
        scope["name"] = target.get("symbol") or target.get("function")
    if target.get("kind") == "va_range":
        scope["kind"] = "va_range"
        scope["va"] = target.get("va")
        scope["end"] = target.get("end")
    return {
        "format": sample.get("format"),
        "arch": sample.get("arch"),
        "bits": sample.get("bits"),
        "endian": sample.get("endian"),
        "target_sha256": sample.get("sha256"),
        "target_scope": scope,
        "allow_whole_image": False,
        "generator": {"generator_id": GENERATOR_ID},
    }


def _reproduce_repair(sample: dict[str, Any]) -> dict[str, Any]:
    from app.services.binary_pipeline import repair_any
    from app.services.poc_runner import load_manifest

    original_path = ROOT / str(sample["source_refs"][0])
    original = original_path.read_bytes()
    oracle_path = ROOT / str(sample["oracle"]["manifest_path"])
    poc_manifest = load_manifest(oracle_path)
    target = _target_argument(sample)
    try:
        outcome = repair_any(
            original,
            poc_manifest=poc_manifest,
            target=target,
            require_target=True,
            allow_whole_image=False,
        )
    except Exception as exc:  # noqa: BLE001 - recorded as not_run, never hidden
        return {
            "status": "not_run",
            "reason": f"repair_any raised {type(exc).__name__}: {exc}",
            "original_path": str(original_path.relative_to(ROOT)),
            "original": original,
            "candidate": None,
            "report": None,
        }
    report = outcome.report
    report_dict = report.to_dict()
    candidate = outcome.candidate
    packet = (
        report.verification.get("packet")
        if isinstance(report.verification, dict) else None
    )
    capacity = packet.get("capacity") if isinstance(packet, dict) else None
    message_actions = (
        list(capacity.get("message_actions") or [])
        if isinstance(capacity, dict) else []
    )
    from app.services import independent_verifier as verifier

    raw_diff_actions = (
        verifier.recompute_actions(original, candidate)
        if candidate is not None else []
    )
    return {
        "status": "reproduced",
        "reason": None,
        "original_path": str(original_path.relative_to(ROOT)),
        "original": original,
        "candidate": candidate,
        "report": report_dict,
        "resolved_scope": dict(report.universal.get("target_scope") or {}),
        "target_policy": report.universal.get("target_policy"),
        "actions": [dict(item) for item in report.actions],
        "message_actions": message_actions,
        "raw_diff_actions": raw_diff_actions,
        "poc_status": (report.poc or {}).get("status"),
        "poc_runner": (report.poc or {}).get("runner"),
        "poc_tier": (report.poc or {}).get("tier"),
        "poc_limitations": list((report.poc or {}).get("limitations") or []),
        "runtime_tier": (report.runtime or {}).get("tier"),
        "gate": report.verification.get("gate")
        if isinstance(report.verification, dict) else None,
        "gate_checks": list(packet.get("checks") or [])
        if isinstance(packet, dict) else [],
        "disposition": report.disposition,
        "strategy": report.strategy,
        "verified": bool(outcome.verified),
        "candidate_sha256": (
            _sha256_bytes(candidate) if candidate is not None else None),
        "patched_sha256": report.patched_sha256,
        "original_sha256": report.original_sha256,
        "oracle_manifest": str(oracle_path.relative_to(ROOT)),
        "ai_invoked": bool(report.ai),
        "message_actions_note": (
            "associated .rodata message alignment actions are produced by the "
            "capacity engine and appear only inside verification.packet.capacity; "
            "report.actions carries rewrite actions only"),
    }


def _checks(report: dict[str, Any]) -> list[dict[str, Any]]:
    return [
        {"id": item.get("id"), "status": item.get("status"),
         "detail": item.get("detail")}
        for item in report.get("checks", [])
    ]


def _cli_verifier(sample: dict[str, Any], original: bytes,
                  candidate: bytes, metadata: dict[str, Any],
                  oracle_path: Path) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="phase8b-verifier-") as tmp:
        tmp_path = Path(tmp)
        candidate_path = tmp_path / "candidate.bin"
        metadata_path = tmp_path / "metadata.json"
        candidate_path.write_bytes(candidate)
        metadata_path.write_text(
            json.dumps(metadata, sort_keys=True) + "\n", encoding="utf-8")
        original_path = ROOT / str(sample["source_refs"][0])
        command = [
            sys.executable, str(ROOT / RUNNER_VERIFIER),
            "--original", str(original_path),
            "--candidate", str(candidate_path),
            "--metadata", str(metadata_path),
            "--poc", str(oracle_path),
            "--json",
        ]
        try:
            result = subprocess.run(
                command, cwd=str(ROOT), capture_output=True, text=True,
                timeout=300,
            )
        except Exception as exc:  # noqa: BLE001
            return {"status": "error",
                    "reason": f"verifier CLI raised {type(exc).__name__}: {exc}"}
    try:
        report = json.loads(result.stdout)
    except json.JSONDecodeError:
        return {"status": "error",
                "reason": f"non-JSON stdout (exit {result.returncode}): "
                          f"{(result.stderr or result.stdout)[:300]}"}
    return {
        "entry_point": "CLI --json",
        "command_template": (
            "scripts/verify_repair.py --original {original} --candidate "
            "{candidate} --metadata {metadata} --poc {oracle} --json"),
        "exit_code": result.returncode,
        "decision": report.get("decision"),
        "checks": _checks(report),
        "limitations": list(report.get("limitations") or []),
        "report_sha256": report.get("report_sha256"),
        "report": report,
    }


def _module_verifier(sample: dict[str, Any], original: bytes,
                     candidate: bytes, metadata: dict[str, Any],
                     oracle_path: Path,
                     run_poc: Any = None,
                     entry_label: str = "module API") -> dict[str, Any]:
    from app.services import independent_verifier as verifier

    try:
        report = verifier.verify_repair(
            original=original,
            candidate=candidate,
            metadata=metadata,
            oracle=str(oracle_path),
            generator={"generator_id": GENERATOR_ID},
            **({"run_poc": run_poc} if run_poc is not None else {}),
        )
    except Exception as exc:  # noqa: BLE001
        return {"status": "error",
                "reason": f"verifier module raised {type(exc).__name__}: {exc}"}
    return {
        "entry_point": entry_label,
        "decision": report.get("decision"),
        "checks": _checks(report),
        "limitations": list(report.get("limitations") or []),
        "report_sha256": report.get("report_sha256"),
        "report": report,
    }


def _elf_va_to_offset(data: bytes, va: int, bits: int) -> int | None:
    if len(data) < 64:
        return None
    try:
        if bits == 64:
            if data[:4] != b"\x7fELF" or data[4] != 2:
                return None
            endian = "<" if data[5] == 1 else ">"
            e_phoff = struct.unpack_from(endian + "Q", data, 32)[0]
            e_phentsize = struct.unpack_from(endian + "H", data, 54)[0]
            e_phnum = struct.unpack_from(endian + "H", data, 56)[0]
            for index in range(e_phnum):
                base = e_phoff + index * e_phentsize
                p_type = struct.unpack_from(endian + "I", data, base)[0]
                if p_type != 1:
                    continue
                p_offset = struct.unpack_from(endian + "Q", data, base + 8)[0]
                p_vaddr = struct.unpack_from(endian + "Q", data, base + 16)[0]
                p_filesz = struct.unpack_from(endian + "Q", data, base + 32)[0]
                if p_vaddr <= va < p_vaddr + p_filesz:
                    return int(p_offset + (va - p_vaddr))
            return None
        if data[:4] != b"\x7fELF" or data[4] != 1:
            return None
        endian = "<" if data[5] == 1 else ">"
        e_phoff = struct.unpack_from(endian + "I", data, 28)[0]
        e_phentsize = struct.unpack_from(endian + "H", data, 42)[0]
        e_phnum = struct.unpack_from(endian + "H", data, 44)[0]
        for index in range(e_phnum):
            base = e_phoff + index * e_phentsize
            p_type = struct.unpack_from(endian + "I", data, base)[0]
            if p_type != 1:
                continue
            p_offset = struct.unpack_from(endian + "I", data, base + 4)[0]
            p_vaddr = struct.unpack_from(endian + "I", data, base + 8)[0]
            p_filesz = struct.unpack_from(endian + "I", data, base + 16)[0]
            if p_vaddr <= va < p_vaddr + p_filesz:
                return int(p_offset + (va - p_vaddr))
        return None
    except struct.error:
        return None


def _experiments(sample: dict[str, Any], repair: dict[str, Any],
                 metadata: dict[str, Any], oracle_path: Path) -> dict[str, Any]:
    from app.services.poc_runner import run_poc

    original = repair["original"]
    candidate = repair["candidate"]
    resolved = repair.get("resolved_scope") or {}
    sample_id = sample["sample_id"]
    experiments: list[dict[str, Any]] = []
    base_module = _module_verifier(sample, original, candidate, metadata,
                                   oracle_path, entry_label="module API")
    experiments.append({
        "id": "E0-module-no-oracle-injection",
        "purpose": "module API without run_poc: verify oracle is not run",
        "hypothesis": "V8B-01",
        "result": base_module,
    })
    with_oracle = _module_verifier(
        sample, original, candidate, metadata, oracle_path,
        run_poc=run_poc, entry_label="module API + run_poc")
    experiments.append({
        "id": "E1-module-with-oracle-injection",
        "purpose": "module API with real run_poc: oracle execution is available",
        "hypothesis": "V8B-01",
        "result": with_oracle,
    })
    enriched = json.loads(json.dumps(metadata))
    if resolved:
        enriched["target_scope"] = {
            "policy": "target_scoped",
            "kind": "va_range",
            "va": int(resolved["va"]),
            "end": int(resolved["end"]),
            "name": resolved.get("name") or "target",
        }
    scope_fixed = _module_verifier(
        sample, original, candidate, enriched, oracle_path,
        run_poc=run_poc, entry_label="module API + resolved scope + oracle")
    experiments.append({
        "id": "E2-resolved-scope-exchange",
        "purpose": "exchange the pipeline-resolved target scope instead of the "
                   "manifest name/range",
        "hypothesis": "V8B-02",
        "resolved_scope": resolved,
        "result": scope_fixed,
    })
    abi_block = None
    if resolved:
        offset = _elf_va_to_offset(original, int(resolved["va"]),
                                   int(sample.get("bits") or 64))
        size = int(resolved["end"]) - int(resolved["va"])
        if offset is not None and size > 0:
            abi_block = {"offset": offset, "size": size}
    abi_enriched = json.loads(json.dumps(enriched))
    if abi_block is not None:
        abi_enriched["abi_block"] = abi_block
    abi_result = _module_verifier(
        sample, original, candidate, abi_enriched, oracle_path,
        run_poc=run_poc, entry_label="module API + resolved scope + abi_block")
    experiments.append({
        "id": "E3-abi-block-derivation",
        "purpose": "derive an ABI block from the resolved code range and feed it "
                   "to the verifier",
        "hypothesis": "V8B-05",
        "derived_abi_block": abi_block,
        "result": abi_result,
    })
    experiments.append({
        "id": "E4-associated-change-modeling",
        "purpose": "check whether the verifier/contract can model the capacity "
                   ".rodata associated change",
        "hypothesis": "V8B-04",
        "message_actions": repair.get("message_actions") or [],
        "raw_diff_actions": repair.get("raw_diff_actions") or [],
        "result": scope_fixed,
        "note": (
            "the verifier recomputes raw byte diffs and target-scope-checks "
            "recomputed actions; the metadata/contract has no associated-change "
            "field, so the .rodata action outside a va_range-only scope fails "
            "closed"),
    })
    return {"sample_id": sample_id, "experiments": experiments}


def _root_causes(sample: dict[str, Any], repair: dict[str, Any],
                 cli: dict[str, Any], module: dict[str, Any],
                 baseline_result: dict[str, Any],
                 experiments: dict[str, Any]) -> list[dict[str, Any]]:
    checks = {item["id"]: item["status"] for item in cli.get("checks", [])}
    module_checks = {item["id"]: item["status"]
                     for item in module.get("checks", [])}
    exp = {item["id"]: item for item in experiments["experiments"]}
    exp_checks = {
        item_id: {check["id"]: check["status"]
                  for check in item["result"].get("checks", [])}
        for item_id, item in exp.items()
    }
    original_size = len(repair["original"])
    candidate = repair.get("candidate")
    candidate_size = len(candidate) if candidate is not None else None
    resized = candidate_size is not None and candidate_size != original_size
    oracle_with = exp_checks["E1-module-with-oracle-injection"].get(
        "runtime-oracle")
    oracle_cli = checks.get("runtime-oracle")
    scope_fixed = exp_checks["E2-resolved-scope-exchange"].get("target-scope")
    abi_with = exp_checks["E3-abi-block-derivation"].get("abi")
    raw_actions = repair.get("raw_diff_actions") or []
    pipeline_actions = repair.get("actions") or []
    message_actions = repair.get("message_actions") or []
    sample_id = sample["sample_id"]
    causes = [
        {
            "hypothesis_id": "V8B-01",
            "title": "oracle exchange: CLI --poc is not wired to run_poc",
            "status": "confirmed",
            "evidence": (
                f"CLI runtime-oracle={oracle_cli!r}; module+run_poc "
                f"runtime-oracle={oracle_with!r}"),
        },
        {
            "hypothesis_id": "V8B-02",
            "title": "resolved target scope is not exchanged",
            "status": "confirmed" if sample_id.startswith("stack") else
                      "not_applicable",
            "evidence": (
                f"manifest target={sample.get('target')!r}; resolved scope="
                f"{repair.get('resolved_scope')!r}; baseline CLI target-scope="
                f"{checks.get('target-scope')!r}; after resolved-scope exchange="
                f"{scope_fixed!r}"),
        },
        {
            "hypothesis_id": "V8B-03",
            "title": "resized/cave candidates are rejected by rewrite-only replay",
            "status": "confirmed" if resized else "refuted_for_observed_sample",
            "evidence": (
                f"original_size={original_size} candidate_size={candidate_size} "
                f"resized={resized}; CLI action-replay="
                f"{checks.get('action-replay')!r}; baseline verifier reason="
                f"{baseline_result.get('verifier_reason')!r}"),
        },
        {
            "hypothesis_id": "V8B-04",
            "title": "associated .rodata message action is not modeled/exchanged; "
                     "gate target-scope only sees report.actions",
            "status": "confirmed",
            "evidence": (
                f"pipeline actions={len(pipeline_actions)}, raw diff actions="
                f"{len(raw_actions)}, capacity message_actions="
                f"{len(message_actions)}; pipeline gate outcome="
                f"{repair.get('gate', {}).get('outcome')!r}; verifier "
                f"target-scope={checks.get('target-scope')!r}"),
        },
        {
            "hypothesis_id": "V8B-05",
            "title": "ABI evidence is not derived/exchanged (metadata.abi_block)",
            "status": "confirmed",
            "evidence": (
                f"runner metadata has no abi_block; baseline verifier abi="
                f"{checks.get('abi')!r}; module abi={module_checks.get('abi')!r}; "
                f"after derived abi_block injection abi={abi_with!r}"),
        },
        {
            "hypothesis_id": "V8B-06",
            "title": "no patch-plan contract is produced or verified",
            "status": "confirmed",
            "evidence": (
                "outcome/metadata carry no plan field; verifier checks have no "
                f"plan check; checks={sorted(checks)}"),
        },
        {
            "hypothesis_id": "V8B-07",
            "title": "benchmark runner does not save/exchange candidate bytes, "
                     "patch plan or verifier report",
            "status": "confirmed",
            "evidence": (
                "runner writes candidate bytes to a temp file for verification "
                "and unlinks it; results.json stores only hashes/counters; the "
                f"artifact directory has no candidate/plan/report (files="
                f"{sorted(p.name for p in (ROOT / RESULTS_PATH).parent.iterdir())})"),
        },
    ]
    return causes


def _sample_packet(sample: dict[str, Any]) -> dict[str, Any]:
    baseline_result = _benchmark_result(sample["sample_id"])
    repair = _reproduce_repair(sample)
    if repair.get("status") != "reproduced" or repair.get("candidate") is None:
        return {
            "sample_id": sample["sample_id"],
            "status": "not_run",
            "reason": repair.get("reason") or "no candidate produced",
            "benchmark_result": baseline_result,
            "repair": {key: value for key, value in repair.items()
                       if key not in {"original", "candidate", "report"}},
            "root_cause_candidates": [],
        }
    metadata = _runner_metadata(sample)
    oracle_path = ROOT / str(sample["oracle"]["manifest_path"])
    original = repair["original"]
    candidate = repair["candidate"]
    result = {
        "sample_id": sample["sample_id"],
        "status": "reproduced",
        "benchmark_result": baseline_result,
        "inputs": {
            "original_path": repair["original_path"],
            "original_sha256": repair["original_sha256"],
            "original_size": len(original),
            "oracle_manifest": repair["oracle_manifest"],
            "manifest_sha256": sample["sha256"],
            "manifest_target": sample.get("target"),
            "recorded_candidate_sha256": baseline_result.get("candidate_sha256"),
        },
        "reproduction": {
            "engine": "app.services.binary_pipeline.repair_any",
            "command": (
                "python - <<'PY' ... repair_any(original, "
                "poc_manifest=load_manifest(oracle), target=..., "
                "require_target=True, allow_whole_image=False)"),
            "disposition": repair.get("disposition"),
            "strategy": repair.get("strategy"),
            "verified_by_generator": repair.get("verified"),
            "poc_status": repair.get("poc_status"),
            "poc_runner": repair.get("poc_runner"),
            "poc_tier": repair.get("poc_tier"),
            "runtime_tier": repair.get("runtime_tier"),
            "gate_outcome": (repair.get("gate") or {}).get("outcome"),
            "gate_success": (repair.get("gate") or {}).get("success"),
            "resolved_scope": repair.get("resolved_scope"),
            "target_policy": repair.get("target_policy"),
            "actions": repair.get("actions"),
            "message_actions": repair.get("message_actions"),
            "raw_diff_actions": repair.get("raw_diff_actions"),
            "candidate_sha256": repair.get("candidate_sha256"),
            "candidate_size": len(candidate),
            "patched_sha256": repair.get("patched_sha256"),
            "ai_invoked": repair.get("ai_invoked"),
            "message_actions_note": repair.get("message_actions_note"),
        },
        "candidate_file": {
            "path": f"disagreement-{sample['sample_id']}/candidate.bin",
            "sha256": repair.get("candidate_sha256"),
            "size": len(candidate),
            "provenance": (
                "deterministic repair_any output from the committed fixture; "
                "evidence-only, non-executable outside the sandbox, not a "
                "correctness claim"),
        },
        "metadata": metadata,
        "verifier": {},
        "root_cause_candidates": [],
        "classification": {},
        "status_flags": {},
    }
    cli = _cli_verifier(sample, original, candidate, metadata, oracle_path)
    module = _module_verifier(sample, original, candidate, metadata,
                              oracle_path, entry_label="module API")
    from app.services.poc_runner import run_poc

    module_oracle = _module_verifier(
        sample, original, candidate, metadata, oracle_path, run_poc=run_poc,
        entry_label="module API + run_poc")
    experiments = _experiments(sample, repair, metadata, oracle_path)
    result["verifier"] = {
        "baseline_runner_path": "CLI --json (the path the benchmark selected)",
        "cli": cli,
        "module_api": module,
        "module_api_with_oracle": module_oracle,
        "experiments": experiments["experiments"],
    }
    causes = _root_causes(sample, repair, cli, module,
                          baseline_result, experiments)
    result["root_cause_candidates"] = causes
    cli_checks = {item["id"]: item["status"] for item in cli.get("checks", [])}
    candidate_matches = (
        repair.get("candidate_sha256") == baseline_result.get("candidate_sha256"))
    result["status_flags"] = {
        "candidate_sha_matches_benchmark": candidate_matches,
        "cli_oracle_not_run": cli_checks.get("runtime-oracle") == "not_run",
        "independently_verified": False,
        "generator_claim_not_copied": True,
    }
    candidate_issue = "none_observed"
    if sample["sample_id"].startswith("stack"):
        classification = {
            "candidate_issue": candidate_issue,
            "verifier_or_exchange_issue": (
                "target-scope exchange missing (symbol not resolved); resized "
                "cave candidate rejected by rewrite-only action replay; ABI and "
                "patch-plan evidence missing; oracle CLI wiring missing"),
            "candidate_correctness": (
                "not verified; independent oracle passed when injected, but the "
                "candidate remains unaccepted because the verifier cannot replay "
                "the resized candidate"),
        }
    else:
        classification = {
            "candidate_issue": candidate_issue,
            "verifier_or_exchange_issue": (
                "associated .rodata message action is not exchanged/modeled; "
                "verifier target-scope rejects the raw-diff action even though "
                "the pipeline gate only checked report.actions; ABI and "
                "patch-plan evidence missing; oracle CLI wiring missing"),
            "candidate_correctness": (
                "not verified; independent oracle passed when injected, but the "
                "candidate remains unaccepted because the associated change and "
                "ABI/plan exchange are absent"),
        }
    result["classification"] = classification
    result["status"] = (
        "reproduced" if candidate_matches else "candidate_sha_mismatch")
    result["_original_bytes"] = original
    result["_candidate_bytes"] = candidate
    return result


