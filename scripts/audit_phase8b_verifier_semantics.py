#!/usr/bin/env python3
"""Phase-8B B1/B2 baseline audit: verifier disagreements and root causes.

Read-only reproduction of the two Phase-8A benchmark disagreements:

* ``stack-strcpy-x86_64`` (guard candidate, resized binary)
* ``heap-capacity-x86_64`` (capacity candidate with a .rodata message action)

For each sample the audit runs the deterministic ``repair_any`` engine (no AI,
no network), saves the original/candidate bytes as evidence-only files, records
the outcome packet/actions/resolved scope/PoC status, and reproduces the current
independent verifier through both entry points (module API and
``scripts/verify_repair.py`` CLI).  Root-cause hypotheses are labelled
confirmed/refuted from measured evidence and focused experiments.

Usage::

    python scripts/audit_phase8b_verifier_semantics.py --write
    python scripts/audit_phase8b_verifier_semantics.py --json
    python scripts/audit_phase8b_verifier_semantics.py --check
    python scripts/audit_phase8b_verifier_semantics.py --reproduce SAMPLE --json

The candidate bytes in the artifact are non-executable evidence generated by
the deterministic engine; the artifact never claims they are correct or
verified.
"""
