def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Phase-8B B1/B2 verifier disagreement baseline audit")
    parser.add_argument("--write", action="store_true",
                        help="reproduce both disagreements and write artifacts")
    parser.add_argument("--check", action="store_true",
                        help="verify committed artifacts/SHA/structure")
    parser.add_argument("--json", action="store_true",
                        help="print the committed baseline summary")
    parser.add_argument("--reproduce", metavar="SAMPLE_ID", default=None,
                        help="re-run one deterministic sample (no repo writes)")
    parser.add_argument("--artifact-dir", type=Path, default=ARTIFACT_DIR)
    args = parser.parse_args(argv)
    if args.check:
        problems = check_artifact(args.artifact_dir)
        if problems:
            for problem in problems:
                print(f"PHASE8B-VIOLATION: {problem}")
            return 1
        print("phase8b-audit: check OK (hashes, candidate bytes, verifier "
              "reports and gap registry verified)")
        return 0
    if args.reproduce:
        print(json.dumps(_reproduce_sample(args.reproduce), indent=2,
                         sort_keys=True, ensure_ascii=True))
        return 0
    if args.write:
        bundle = build_artifact()
        baseline = bundle["baseline"]
        violations = _validate_document(baseline) + _validate_gaps(bundle["gaps"])
        if violations:
            print("PHASE8B-VIOLATION: refusing to write an invalid baseline")
            for violation in violations:
                print(f"PHASE8B-VIOLATION: {violation}")
            return 1
        artifacts = write_artifacts(bundle, args.artifact_dir)
        print(f"phase8b-audit: wrote {artifacts['artifact_dir']}")
        print("summary_status=" + str(baseline["summary"]["status"]))
        for sample in bundle["samples"]:
            print(f"{sample['sample_id']}: status={sample.get('status')} "
                  f"candidate_sha256={sample.get('reproduction', {}).get('candidate_sha256')}")
        print("gaps=" + ",".join(item["id"] for item in bundle["gaps"]["items"]))
        for name in sorted(artifacts["sha256"]):
            print(f"{name}_sha256={artifacts['sha256'][name]}")
        return 0
    baseline_path = args.artifact_dir / "phase8b-baseline-audit.json"
    if not baseline_path.is_file():
        print("phase8b-audit: no committed baseline; run --write first")
        return 1
    baseline = _load_json(baseline_path)
    summary = baseline.get("summary", {})
    payload = {
        "base_sha": baseline.get("base_sha"),
        "status": summary.get("status"),
        "samples": summary.get("samples"),
        "gap_ids": summary.get("gap_registry", {}).get("ids"),
        "dynamic_oracle": summary.get("dynamic_oracle"),
        "capability_claims": baseline.get("capability_claims"),
    }
    print(json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
