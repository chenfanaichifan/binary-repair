def write_artifacts(bundle: dict[str, Any],
                    artifact_dir: Path = ARTIFACT_DIR) -> dict[str, Any]:
    target = Path(artifact_dir)
    target.mkdir(parents=True, exist_ok=True)
    baseline = bundle["baseline"]
    gaps = bundle["gaps"]
    samples = bundle["samples"]
    (target / "phase8b-baseline-audit.json").write_text(
        _canonical_json(baseline), encoding="utf-8")
    (target / "phase8b-verifier-gap-registry.json").write_text(
        _canonical_json(gaps), encoding="utf-8")
    written: list[str] = [
        "phase8b-baseline-audit.json", "phase8b-verifier-gap-registry.json"]
    for sample in samples:
        directory = target / _sample_dir_name(sample["sample_id"])
        directory.mkdir(parents=True, exist_ok=True)
        original_bytes = sample.get("_original_bytes")
        candidate_bytes = sample.get("_candidate_bytes")
        if original_bytes is None:
            raise ValueError(f"{sample['sample_id']}: no saved original bytes")
        (directory / "original.elf").write_bytes(original_bytes)
        if candidate_bytes is not None:
            (directory / "candidate.bin").write_bytes(candidate_bytes)
        (directory / "outcome.json").write_text(
            _canonical_json(_outcome_file(sample)), encoding="utf-8")
        (directory / "metadata.json").write_text(
            _canonical_json(_metadata_file(sample)), encoding="utf-8")
        (directory / "verifier-report.json").write_text(
            _canonical_json(_verifier_report_file(sample)), encoding="utf-8")
        script = _reproduce_script(sample)
        script_path = directory / "reproduce.sh"
        script_path.write_text(script, encoding="utf-8")
        script_path.chmod(0o755)
        written.extend([
            f"{directory.name}/original.elf",
            f"{directory.name}/candidate.bin",
            f"{directory.name}/outcome.json",
            f"{directory.name}/metadata.json",
            f"{directory.name}/verifier-report.json",
            f"{directory.name}/reproduce.sh",
        ])
    readme = _readme(bundle)
    (target / "README.md").write_text(readme, encoding="utf-8")
    written.append("README.md")
    docs = [DOC_DISAGREEMENT, DOC_IMPLEMENTATION, DOC_TEST_PLAN]
    missing_docs = [path for path in docs if not (ROOT / path).is_file()]
    if missing_docs:
        raise FileNotFoundError(f"missing required docs: {missing_docs}")
    lines = []
    for relative in written:
        path = target / relative
        lines.append(f"{_sha256_file(path)}  {relative}")
    for doc in docs:
        path = ROOT / doc
        lines.append(f"{_sha256_file(path)}  ../../{doc}")
    (target / "SHA256SUMS").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {
        "artifact_dir": str(target),
        "files": written,
        "sha256": {relative: _sha256_file(target / relative)
                   for relative in written},
        "suits": _sha256_file(target / "SHA256SUMS"),
    }


