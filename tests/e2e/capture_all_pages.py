"""Capture every reachable page / state of the DeepSeek-style UI.

Run from the project root:
    .venv/Scripts/python.exe tests/e2e/capture_all_pages.py

Output: docs/screenshots/pages/*.png
Covers the home page, the agent console (guided / question / review / pending /
success / failure / live job), the original setup wizard steps, and the job
progress / evidence / report pages.
"""

from __future__ import annotations

import base64
import re
import socket
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

import httpx  # noqa: E402

from cdp import find_edge, launch_browser, stop_browser  # noqa: E402
from conftest import start_gui, stop_gui  # noqa: E402
from config import SESSION_TOKEN  # noqa: E402

OUT = ROOT / "docs" / "screenshots" / "pages"


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def main() -> int:
    edge = find_edge()
    if edge is None:
        print("Microsoft Edge is not installed; cannot capture screenshots")
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    process, base_url = start_gui(
        {"BINARYREPAIR_BACKEND": "mock", "BINARYREPAIR_SESSION_TOKEN": SESSION_TOKEN}
    )
    browser = None
    session = None
    try:
        # Create a real (mock) job so the original pages have data to show.
        http = httpx.Client(base_url=base_url, timeout=20)
        http.get("/?token=" + SESSION_TOKEN)
        # CSRF is generated by the server process, so read it from the form.
        setup_html = http.get("/jobs/new").text
        csrf = re.search(r'name="csrf" value="([^"]+)"', setup_html).group(1)
        created = http.post(
            "/jobs",
            data={
                "defect": "strcpy in stack_buf does not check length; overlong input writes out of bounds",
                "valid_tests": "valid: hello\nboundary: 8 bytes\ninvalid: 512 bytes",
                "environment": "Ubuntu x86-64 VM (test: execution disabled)",
                "valid_domain": "Input length 0-64 bytes",
                "forbidden": "Out-of-bounds write to the target buffer",
                "invalid_outcome": "Return error code 1 without out-of-bounds access",
                "assumptions": "Single process",
                "csrf": csrf,
            },
            files={"binary": ("sample.elf", b"\x7fELF" + b"demo" * 64, "application/octet-stream")},
            follow_redirects=False,
        )
        job_id = created.headers["location"].rstrip("/").rsplit("/", 1)[-1]
        print("job:", job_id)

        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as profile:
            browser, session = launch_browser(edge, _free_port(), Path(profile))
            session.send(
                "Emulation.setDeviceMetricsOverride",
                {"width": 1440, "height": 1000, "deviceScaleFactor": 1, "mobile": False},
            )
            session.navigate(base_url + "/?token=" + SESSION_TOKEN)

            sample = Path(profile) / "sample.elf"
            sample.write_bytes(b"\x7fELF" + b"demo-bytes" * 32)

            def shot(name: str, full: bool = False) -> None:
                time.sleep(0.7)
                params = {"format": "png"}
                if full:
                    params["captureBeyondViewport"] = True
                data = session.send("Page.captureScreenshot", params)["data"]
                (OUT / name).write_bytes(base64.b64decode(data))
                print("saved", name)

            def go(path: str) -> None:
                session.navigate(base_url + path)
                time.sleep(0.4)

            # 01 起始页
            go("/")
            shot("01-home.png", full=True)

            # 02 控制台 · 引导首屏（上传卡）
            go("/agent?fixture=1")
            session.wait_js('document.querySelector(\'[data-testid="agent-dropzone"]\') !== null')
            shot("02-agent-guided.png")

            # 03 控制台 · 问题卡（真实读取样本后）
            go("/agent?plan=fixture")
            session.wait_js('document.querySelector(\'[data-testid="agent-dropzone"]\') !== null')
            session.set_file_input('[data-testid="agent-file-input"]', str(sample))
            session.wait_js('document.querySelector(\'[data-testid="agent-field-defect"]\') !== null')
            shot("03-agent-question.png")

            # 04 控制台 · 复核卡
            for index in (1, 2, 3):
                session.eval_js(
                    "(() => {var n=document.querySelectorAll('[data-testid=\"agent-question-default\"]');"
                    "if(n.length) n[n.length-1].click(); return true;})()"
                )
                session.eval_js(
                    "(() => {var n=document.querySelectorAll('[data-testid=\"agent-question-next\"]');"
                    "if(n.length) n[n.length-1].click(); return true;})()"
                )
                time.sleep(0.3)
            session.wait_js('document.querySelector(\'[data-testid="agent-review-card"]\') !== null')
            shot("04-agent-review.png")

            # 05 等待回传
            go("/agent?fixture=1&scenario=pending")
            session.click('[data-testid="agent-tab-result"]')
            session.wait_js('!document.querySelector(\'[data-testid="agent-receipt-placeholder"]\').hidden')
            shot("05-agent-pending.png")

            # 06 成功 · 结果屏
            go("/agent?fixture=1&scenario=success")
            session.click('[data-testid="agent-tab-result"]')
            session.wait_js('document.querySelector(\'[data-testid="agent-before-after"] pre\') !== null')
            shot("06-agent-success.png")

            # 07 失败 · 结果屏
            go("/agent?fixture=1&scenario=failure")
            session.click('[data-testid="agent-tab-result"]')
            session.wait_js('document.querySelector(\'[data-testid="agent-obligations"]\') !== null')
            shot("07-agent-failure.png")

            # 08 成功 · 对话屏（含 llm 徽章与降级横幅）
            go("/agent?fixture=1&scenario=success")
            session.wait_js('!document.querySelector(\'[data-testid="agent-fallback"]\').hidden')
            shot("08-agent-success-chat.png")

            # 09-11 原有表单向导
            go("/jobs/new")
            shot("09-setup-home.png", full=True)
            session.click('[data-testid="choice-input"]')
            session.set_file_input('[data-testid="binary-input"]', str(sample))
            session.eval_js(
                "(() => {"
                "var d=document.querySelector('[data-testid=\"defect-input\"]');"
                "d.value='strcpy in stack_buf does not check length; overlong input writes out of bounds';"
                "d.dispatchEvent(new Event('input',{bubbles:true}));"
                "var t=document.querySelector('[data-testid=\"tests-input\"]');"
                "t.value='valid: hello\\nboundary: 8 bytes\\ninvalid: 64 bytes';"
                "t.dispatchEvent(new Event('input',{bubbles:true}));"
                "var e=document.querySelector('[data-testid=\"env-input\"]');"
                "e.value='Ubuntu x86-64 VM (execution disabled in demo)';"
                "e.dispatchEvent(new Event('input',{bubbles:true}));"
                "return true;})()"
            )
            time.sleep(0.3)
            shot("10-setup-input.png", full=True)
            session.click('[data-testid="wizard-next"]')
            session.wait_js(
                '!document.querySelector(\'[data-testid="contract-domain"]\').closest(".wizard-view").hidden'
            )
            time.sleep(0.3)
            shot("11-setup-contract.png", full=True)

            # 12-13 原有进度 / 证据页
            go(f"/jobs/{job_id}")
            time.sleep(1.2)
            shot("12-job-progress.png", full=True)
            go(f"/jobs/{job_id}/evidence")
            time.sleep(0.6)
            shot("13-job-evidence.png", full=True)

            # 14 控制台打开真实任务
            go(f"/agent?job={job_id}")
            time.sleep(1.2)
            shot("14-agent-live-job.png")

            # 15 HTML 报告
            go(f"/jobs/{job_id}/report")
            time.sleep(0.6)
            shot("15-job-report.png", full=True)

            # 16 控制台真实模式（无引导计划时的诚实提示）
            go("/agent")
            time.sleep(0.5)
            shot("16-agent-live-empty.png")

        http.close()
    finally:
        if session is not None:
            stop_browser(browser, session)
        stop_gui(process)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
